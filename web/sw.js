// Caches the app shell so pneuma opens instantly (and installs as a PWA).
// Messages and files always come from the network.
const CACHE = "pneuma-shell-v7";
const SHELL = ["/", "/app.js", "/style.css", "/manifest.webmanifest", "/icons/logo.svg", "/fonts/jetbrains-mono-400.woff2", "/fonts/jetbrains-mono-700.woff2", "/fonts/bytesized.woff2"];

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== "GET" || url.origin !== location.origin) return;
  if (url.pathname.startsWith("/api/") || url.pathname.startsWith("/f/")) return;
  // Network first, so a redeploy is picked up straight away.
  e.respondWith(
    fetch(e.request)
      .then((res) => {
        if (res.ok) {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(e.request, copy));
        }
        return res;
      })
      .catch(() => caches.match(e.request, { ignoreSearch: true })),
  );
});
